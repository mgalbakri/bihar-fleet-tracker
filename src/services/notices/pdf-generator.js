// PDF Generator -- generates notice PDFs for archival and attachment
const fs = require('fs');
const path = require('path');
const { v4: uuidv4 } = require('uuid');

const NOTICES_DIR = path.join(__dirname, '..', '..', '..', 'data', 'notices');

function init() {
  if (!fs.existsSync(NOTICES_DIR)) {
    fs.mkdirSync(NOTICES_DIR, { recursive: true });
  }
}

/**
 * Generate a plain-text notice file (PDF generation requires pdfkit -- fallback to .txt)
 * When pdfkit is installed, this generates a real PDF. Otherwise, generates a formatted text file.
 * @param {Object} notice - Notice record from DB
 * @returns {{ filePath: string, fileName: string }}
 */
function generateNoticePDF(notice) {
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const fileName = `${notice.notice_type}-${notice.vessel_imo}-${timestamp}`;

  try {
    // Try pdfkit if available
    const PDFDocument = require('pdfkit');
    const pdfPath = path.join(NOTICES_DIR, fileName + '.pdf');
    const doc = new PDFDocument({ margin: 50 });
    const stream = fs.createWriteStream(pdfPath);
    doc.pipe(stream);

    // Header
    doc.fontSize(10).fillColor('#666').text('CONFIDENTIAL', { align: 'right' });
    doc.moveDown(0.5);
    doc.fontSize(18).fillColor('#0f172a').text('BIHAR SENTINEL', { align: 'center' });
    doc.fontSize(10).fillColor('#666').text('Maritime Intelligence. Threat Awareness. Fleet Protection.', { align: 'center' });
    doc.moveDown(1);

    // Notice type banner
    doc.fontSize(14).fillColor('#ef4444').text(notice.notice_type + ' NOTICE', { align: 'center' });
    doc.moveDown(0.5);

    // Vessel details
    doc.fontSize(10).fillColor('#333');
    doc.text(`Vessel: ${notice.vessel_name} (IMO: ${notice.vessel_imo})`);
    doc.text(`Generated: ${notice.generated_at}`);
    doc.text(`Due By: ${notice.due_by || 'N/A'}`);
    doc.text(`Status: ${notice.status}`);
    doc.text(`Policy Ref: ${notice.policy_ref || 'N/A'}`);
    doc.moveDown(1);

    // Divider
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke('#ccc');
    doc.moveDown(1);

    // Content
    doc.fontSize(10).fillColor('#000');
    // Strip HTML tags for PDF content
    const plainContent = (notice.notice_content || '').replace(/<[^>]*>/g, '').replace(/&nbsp;/g, ' ');
    doc.text(plainContent, { width: 500, lineGap: 4 });

    doc.moveDown(2);

    // Footer
    doc.fontSize(8).fillColor('#999');
    doc.text('This document is generated by BIHAR SENTINEL and is classified as CONFIDENTIAL.', { align: 'center' });
    doc.text('Distribution restricted to authorized personnel only.', { align: 'center' });

    doc.end();
    return { filePath: pdfPath, fileName: fileName + '.pdf' };

  } catch (err) {
    // Fallback: generate text file
    const txtPath = path.join(NOTICES_DIR, fileName + '.txt');
    const content = [
      '═══════════════════════════════════════════════════════════════',
      '                     BIHAR SENTINEL                           ',
      '          Maritime Intelligence. Threat Awareness.             ',
      '═══════════════════════════════════════════════════════════════',
      '',
      `NOTICE TYPE: ${notice.notice_type}`,
      `VESSEL:      ${notice.vessel_name} (IMO: ${notice.vessel_imo})`,
      `GENERATED:   ${notice.generated_at}`,
      `DUE BY:      ${notice.due_by || 'N/A'}`,
      `STATUS:      ${notice.status}`,
      `POLICY REF:  ${notice.policy_ref || 'N/A'}`,
      '',
      '───────────────────────────────────────────────────────────────',
      '',
      (notice.notice_content || '').replace(/<[^>]*>/g, ''),
      '',
      '───────────────────────────────────────────────────────────────',
      'CONFIDENTIAL - BIHAR SENTINEL',
      '═══════════════════════════════════════════════════════════════'
    ].join('\n');

    fs.writeFileSync(txtPath, content, 'utf8');
    return { filePath: txtPath, fileName: fileName + '.txt' };
  }
}

/**
 * Get the file path for a notice PDF
 */
function getNoticePDF(noticeId, db) {
  if (!db) return null;
  const notice = db.prepare('SELECT pdf_path FROM insurer_notices WHERE id = ?').get(noticeId);
  if (notice && notice.pdf_path && fs.existsSync(notice.pdf_path)) {
    return notice.pdf_path;
  }
  return null;
}

module.exports = { init, generateNoticePDF, getNoticePDF };
